import assert from "node:assert/strict";
import {chromium} from "playwright";
const origin="https://end-to-end-everywhere-standard.onrender.com";
const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
const errors=[];
try{
  const page=await browser.newPage({viewport:{width:1320,height:860}});
  page.on("pageerror",error=>errors.push(error.message));
  await page.goto(origin+"/",{waitUntil:"domcontentloaded",timeout:45000});
  await page.locator(".hero h1").waitFor({timeout:20000});
  const metrics=await page.locator(".metric b").allTextContents();
  assert.ok(Number(metrics[0])>=20&&Number(metrics[1])>=50&&Number(metrics[2])>=50,"Catalog not populated");
  console.log("Browser homepage and "+metrics.join("/")+" source-backed counts passed.");
  await page.locator(".hero a[data-route=guide]").click();
  await page.locator("h1").filter({hasText:"What are you building?"}).waitFor();
  await page.locator("input[data-choice=messages]").check();
  await page.locator("#guide-result .filter-btn").first().waitFor();
  console.log("Browser guided discovery and interactive capability filters passed.");
  await page.locator('.sidebar [data-nav="profiles"]').click();
  await page.locator(".profile-card").first().waitFor();
  await page.locator(".profile-card").first().click();
  await page.locator(".detail-panel").first().waitFor();
  console.log("Browser profile listing to detail navigation passed.");
  await page.locator('.sidebar [data-nav="library"]').click();
  await page.locator(".doc-card").first().waitFor();
  await page.locator(".doc-card").first().click();
  await page.locator(".reader-article h1").first().waitFor();
  console.log("Browser library to full source-backed Markdown document passed.");
  await page.goto(origin+"/");
  await page.locator(".hero h1").waitFor();
  await page.locator("#site-search").fill("pairwise");
  await page.locator("#search-results .search-hit").first().waitFor();
  console.log("Browser text search returns navigable matches.");
  const phone=await browser.newPage({viewport:{width:390,height:840}});
  phone.on("pageerror",error=>errors.push(error.message));
  await phone.goto(origin+"/",{waitUntil:"domcontentloaded",timeout:45000});
  await phone.locator(".hero h1").waitFor();
  await phone.locator("#menu-button").click();
  await phone.locator('.sidebar.open [data-nav="library"]').click();
  await phone.locator(".doc-card").first().waitFor();
  console.log("Mobile menu and library navigation passed.");
  const preview=await browser.newPage({viewport:{width:1320,height:850}});
  preview.on("pageerror",error=>{errors.push(error.message);console.log("PREVIEW PAGE ERROR:",JSON.stringify({name:error.name,message:error.message,stack:error.stack,raw:String(error)}))});
  preview.on("response",async response=>{if(response.url().includes("app.js")||response.url().includes("standard.json")){try{const body=await response.text();const sig=body.slice(0,150);console.log("PREVIEW RESOURCE:",JSON.stringify({url:response.url(),status:response.status(),type:response.headers()["content-type"],bytes:body.length,start:sig}))}catch(e){console.log("PREVIEW RESOURCE READ FAILURE",String(e))}}});
  preview.on("console",message=>{if(message.type()==="error")console.log("PREVIEW CONSOLE ERROR:",message.text())});
  preview.on("requestfailed",request=>console.log("PREVIEW REQUEST FAILED:",request.url(),request.failure()?.errorText));
  const previewResponse=await preview.goto("https://e2eesa-standards-portal.onrender.com/",{waitUntil:"domcontentloaded",timeout:45000});
  console.log("PREVIEW NAVIGATION:",previewResponse?.status(),preview.url());
  try{await preview.locator(".hero h1").waitFor({timeout:9000})}catch(err){
    console.log("PREVIEW DOCUMENT BODY:",(await preview.locator("body").innerText()).slice(0,2500));
    console.log("PREVIEW APP:",(await preview.locator("#app").innerHTML()).slice(0,1800));
    console.log("PREVIEW RESOURCES:",JSON.stringify(await preview.evaluate(()=>performance.getEntriesByType("resource").map(x=>x.name))));
    throw err;
  }
  await preview.locator('.sidebar [data-nav="library"]').click();
  await preview.locator(".doc-card").first().waitFor();
  await preview.locator(".doc-card").first().click();
  await preview.locator(".reader-article h1").first().waitFor({timeout:20000});
  console.log("Legacy preview URL: homepage, library navigation and full-document reading passed.");
  assert.deepEqual(errors,[],"Live page threw browser exceptions");
  console.log("LIVE BROWSER ACCEPTANCE PASSED.");
}finally{await browser.close()}
